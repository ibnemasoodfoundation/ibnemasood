/* Photo and document uploads for branches and Makatib.
   Files are stored under uploads/ (outside public/) with random names and are only
   served to signed-in staff through /app/files/:id. */
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const multer = require("multer");

const UPLOAD_DIR = path.resolve(process.env.UPLOAD_DIR || path.join(__dirname, "..", "uploads"));

const TYPES = {
  photo: {
    max: 5 * 1024 * 1024,
    ext: { ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".webp": "image/webp" },
    label: "JPG, PNG or WebP, up to 5 MB",
  },
  document: {
    max: 10 * 1024 * 1024,
    ext: {
      ".pdf": "application/pdf", ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".webp": "image/webp",
      ".doc": "application/msword",
      ".docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
      ".xls": "application/vnd.ms-excel",
      ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    },
    label: "PDF, Word, Excel or image, up to 10 MB",
  },
};

const storage = multer.diskStorage({
  destination: (req, file, cb) => {
    fs.mkdirSync(UPLOAD_DIR, { recursive: true });
    cb(null, UPLOAD_DIR);
  },
  filename: (req, file, cb) => cb(null, crypto.randomBytes(16).toString("hex") + path.extname(file.originalname).toLowerCase()),
});

/* Express middleware: accepts one file in field "file"; kind comes from ?kind=photo|document */
function acceptUpload(req, res, next) {
  const kind = req.query.kind === "photo" ? "photo" : "document";
  const rule = TYPES[kind];
  const upload = multer({
    storage,
    limits: { fileSize: rule.max, files: 1, fields: 5 },
    fileFilter: (r, file, cb) => {
      const ext = path.extname(file.originalname).toLowerCase();
      cb(null, rule.ext[ext] !== undefined && rule.ext[ext] === file.mimetype);
    },
  }).single("file");

  upload(req, res, (err) => {
    req.uploadKind = kind;
    if (err) req.uploadError = err.code === "LIMIT_FILE_SIZE" ? `That file is too large (${rule.label}).` : "The upload could not be read. Please try again.";
    else if (!req.file) req.uploadError = `Choose a file of the right type (${rule.label}).`;
    next();
  });
}

function filePath(storedName) {
  // stored names are generated by us: 32 hex chars + extension; reject anything else
  if (!/^[0-9a-f]{32}\.[a-z0-9]{2,5}$/.test(storedName)) return null;
  return path.join(UPLOAD_DIR, storedName);
}

function removeFile(storedName) {
  const p = filePath(storedName);
  if (p) fs.rm(p, { force: true }, () => {});
}

module.exports = { acceptUpload, filePath, removeFile, TYPES };
