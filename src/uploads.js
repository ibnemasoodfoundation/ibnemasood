/* Photo and document uploads.
   Files get random names and are only served through /app/files/:id (staff) or /media/:id (approved photos).
   Locally they are stored under uploads/ (outside public/). When SUPABASE_URL and SUPABASE_SECRET_KEY are set
   (needed on Vercel, whose disk is read-only) they go to a private Supabase Storage bucket instead. */
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const multer = require("multer");

const UPLOAD_DIR = path.resolve(process.env.UPLOAD_DIR || path.join(__dirname, "..", "uploads"));

const TYPES = {
  photo: {
    max: 5 * 1024 * 1024,
    ext: { ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".webp": "image/webp" },
    label: "JPG, PNG or WebP, up to 5 MB",
  },
  document: {
    max: 10 * 1024 * 1024,
    ext: {
      ".pdf": "application/pdf", ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".webp": "image/webp",
      ".doc": "application/msword",
      ".docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
      ".xls": "application/vnd.ms-excel",
      ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    },
    label: "PDF, Word, Excel or image, up to 10 MB",
  },
};

const SUPABASE_URL = (process.env.SUPABASE_URL || "").replace(/\/+$/, "");
const SUPABASE_KEY = process.env.SUPABASE_SECRET_KEY || "";
const BUCKET = process.env.SUPABASE_BUCKET || "uploads";
const remote = Boolean(SUPABASE_URL && SUPABASE_KEY);

function storageFetch(pathname, init = {}) {
  return fetch(`${SUPABASE_URL}/storage/v1/${pathname}`, {
    ...init,
    headers: { apikey: SUPABASE_KEY, Authorization: `Bearer ${SUPABASE_KEY}`, ...init.headers },
  });
}

// Creates the private bucket on first use; "already exists" is fine
let bucketReady = null;
function ensureBucket() {
  if (!bucketReady) bucketReady = storageFetch("bucket", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ id: BUCKET, name: BUCKET, public: false }),
  }).then(async (r) => {
    if (!r.ok && r.status !== 409 && !/already exists/i.test(await r.text())) throw new Error(`Storage bucket: HTTP ${r.status}`);
  }).catch((err) => { bucketReady = null; throw err; });
  return bucketReady;
}

async function putRemote(file) {
  await ensureBucket();
  const r = await storageFetch(`object/${BUCKET}/${file.filename}`, {
    method: "POST",
    headers: { "Content-Type": file.mimetype, "x-upsert": "false" },
    body: file.buffer,
  });
  if (!r.ok) throw new Error(`Storage upload: HTTP ${r.status}`);
}

const randomName = (file) => crypto.randomBytes(16).toString("hex") + path.extname(file.originalname).toLowerCase();

const storage = remote ? multer.memoryStorage() : multer.diskStorage({
  destination: (req, file, cb) => {
    fs.mkdirSync(UPLOAD_DIR, { recursive: true });
    cb(null, UPLOAD_DIR);
  },
  filename: (req, file, cb) => cb(null, randomName(file)),
});

/* Express middleware: accepts one file in field "file"; kind comes from ?kind=photo|document */
function acceptUpload(req, res, next) {
  const kind = req.query.kind === "photo" ? "photo" : "document";
  const rule = TYPES[kind];
  const upload = multer({
    storage,
    limits: { fileSize: rule.max, files: 1, fields: 5 },
    fileFilter: (r, file, cb) => {
      const ext = path.extname(file.originalname).toLowerCase();
      cb(null, rule.ext[ext] !== undefined && rule.ext[ext] === file.mimetype);
    },
  }).single("file");

  upload(req, res, async (err) => {
    req.uploadKind = kind;
    if (err) req.uploadError = err.code === "LIMIT_FILE_SIZE" ? `That file is too large (${rule.label}).` : "The upload could not be read. Please try again.";
    else if (!req.file) req.uploadError = `Choose a file of the right type (${rule.label}).`;
    else if (remote) {
      req.file.filename = randomName(req.file);
      try { await putRemote(req.file); }
      catch (e) {
        console.error(e.message);
        req.file = null;
        req.uploadError = "The file could not be saved. Please try again.";
      }
      if (req.file) req.file.buffer = null;
    }
    next();
  });
}

// stored names are generated by us: 32 hex chars + extension; reject anything else
const validName = (storedName) => /^[0-9a-f]{32}\.[a-z0-9]{2,5}$/.test(storedName || "");

/* Sends a stored file; resolves false when it does not exist (the caller answers 404) */
async function sendStored(res, storedName, mime) {
  if (!validName(storedName)) return false;
  if (!remote) {
    return new Promise((resolve) => {
      res.type(mime).sendFile(path.join(UPLOAD_DIR, storedName), (err) => resolve(!(err && !res.headersSent)));
    });
  }
  const r = await storageFetch(`object/authenticated/${BUCKET}/${storedName}`).catch(() => null);
  if (!r || !r.ok) return false;
  res.type(mime).send(Buffer.from(await r.arrayBuffer()));
  return true;
}

function removeFile(storedName) {
  if (!validName(storedName)) return;
  if (remote) {
    storageFetch(`object/${BUCKET}/${storedName}`, { method: "DELETE" }).catch((e) => console.error("Storage delete:", e.message));
  } else {
    fs.rm(path.join(UPLOAD_DIR, storedName), { force: true }, () => {});
  }
}

module.exports = { acceptUpload, sendStored, removeFile, TYPES, remote };
